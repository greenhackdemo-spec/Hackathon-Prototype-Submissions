import { Product } from '../types.ts';
import { computeEcoScores, determineSustainabilityStatus } from '../services/scoringService.ts';

function createProduct(partial: Omit<Product, 'scores' | 'status'>): Product {
  const scores = computeEcoScores(partial);
  const status = determineSustainabilityStatus(scores.totalScore, partial);
  return {
    ...partial,
    scores,
    status,
  };
}

